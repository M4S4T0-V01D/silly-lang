#!/usr/bin/env python3
"""Rasterize the gfx module's built-in fonts into silly/std/gfx_font.c.

Needs Pillow and the DejaVu fonts. The output is checked in, so this only runs
when the fonts change:

    python3 tools/genfont.py [DEJAVU_DIR]

Each font covers U+0020..U+00FF. Glyphs are 4-bit coverage masks, one character
per pixel ('1'-'9', 'A'-'F' are levels 1-15), with runs of transparent pixels
written as 'g'..'z' (1-20 zeros). gf_decode in gfx.c expands them on first use.
"""

import os
import sys

from PIL import ImageFont

FONTS = [  # (C name, file, pixel size)
    ("sans", "DejaVuSans.ttf", 13),
    ("bold", "DejaVuSans-Bold.ttf", 13),
    ("mono", "DejaVuSansMono.ttf", 13),
    ("small", "DejaVuSans.ttf", 11),
    ("heading", "DejaVuSans-Bold.ttf", 17),
    ("title", "DejaVuSans-Bold.ttf", 26),
]
FIRST, LAST = 0x20, 0xFF
LICENSE = """\
 * Glyphs rasterized from the DejaVu fonts (https://dejavu-fonts.github.io/).
 * DejaVu changes are in the public domain. Bitstream Vera glyphs:
 * Copyright (c) 2003 by Bitstream, Inc. All Rights Reserved. Bitstream Vera is
 * a trademark of Bitstream, Inc. Permission is hereby granted, free of charge,
 * to any person obtaining a copy of the fonts accompanying this license and
 * associated documentation files, to reproduce and distribute the Font
 * Software, including without limitation the rights to use, copy, merge,
 * publish, distribute, and/or sell copies of the Font Software, subject to
 * the conditions in the Bitstream Vera license (see docs/licenses/dejavu.txt).
 * The fonts here are bitmaps derived from them and carry no Bitstream names."""


def encode(levels):
    out, zeros = [], 0
    for v in levels + [None]:
        if v == 0:
            zeros += 1
            if zeros == 20:
                out.append("z")
                zeros = 0
            continue
        if zeros:
            out.append(chr(ord("f") + zeros))
            zeros = 0
        if v is not None:
            out.append("0123456789ABCDEF"[v])
    return "".join(out)


def font_c(cname, path, size):
    f = ImageFont.truetype(path, size)
    ascent, descent = f.getmetrics()
    glyphs, data = [], []
    off = 0
    for cp in range(FIRST, LAST + 1):
        ch = chr(cp) if not (0x7F <= cp < 0xA0) else "?"
        adv = round(f.getlength(ch))
        m, offset = f.getmask2(ch, mode="L")
        w, h = m.size
        px = [m.getpixel((x, y)) for y in range(h) for x in range(w)]
        levels = [(p + 8) // 17 for p in px]
        enc = encode(levels)
        glyphs.append(f"{{{adv}, {offset[0]}, {offset[1]}, {w}, {h}, {off}}}")
        data.append(enc)
        off += len(enc)
    lines = [f"static const gf_glyph gf_{cname}_glyphs[{LAST - FIRST + 1}] = {{"]
    for i in range(0, len(glyphs), 6):
        lines.append("    " + ", ".join(glyphs[i:i + 6]) + ",")
    lines.append("};")
    blob = "".join(data)
    lines.append(f"static const char gf_{cname}_bits[] =")
    for i in range(0, len(blob), 100):
        lines.append(f'    "{blob[i:i + 100]}"')
    lines.append(";")
    lines.append(f"static gf_font gf_{cname} = {{{ascent + descent}, {ascent}, {len(blob)}, "
                 f"gf_{cname}_glyphs, gf_{cname}_bits, 0}};")
    return "\n".join(lines)


def main():
    d = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/TTF"
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    parts = ["/* Generated by tools/genfont.py; do not edit.\n *\n" + LICENSE + "\n */",
             "typedef struct { int16_t adv, x, y, w, h; int32_t off; } gf_glyph;",
             "typedef struct { int16_t height, ascent; int32_t nbits; const gf_glyph *g; const char *src;"
             " uint8_t *bits; } gf_font;"]
    for cname, file, size in FONTS:
        parts.append(font_c(cname, os.path.join(d, file), size))
    parts.append("static gf_font *const gf_fonts[] = {" + ", ".join(f"&gf_{c}" for c, _, _ in FONTS) + "};")
    parts.append(f"#define GF_NFONTS {len(FONTS)}")
    out = os.path.join(root, "silly", "std", "gfx_font.c")
    with open(out, "w") as fh:
        fh.write("\n\n".join(parts) + "\n")
    print(f"wrote {out} ({os.path.getsize(out) // 1024} KB)")


if __name__ == "__main__":
    main()
