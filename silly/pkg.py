"""Packages: silly.toml manifests, path and git dependencies, silly.lock.

A package is a directory with a silly.toml and a src/ folder:

    [package]
    name = "shapes"
    version = "0.1.0"
    entry = "src/main.silly"      # optional; this is the default

    [dependencies]
    vec2 = { path = "../vec2" }
    color = { git = "https://example.com/color.git", rev = "v1.2" }

`import vec2.ops` loads <vec2>/src/ops.silly and a bare `import vec2` loads
<vec2>/src/lib.silly.  The package can import its own modules through its own
name too.  Dependencies are resolved transitively into one flat set: a name
must come from a single source, or resolution fails.  Git checkouts live in
.silly/deps/<name> next to the root manifest, and silly.lock records the exact
commit of each one so every build of the project sees the same code.
"""

import json
import os
import re
import subprocess
import tomllib

from .errors import SillyError

MANIFEST = "silly.toml"
LOCKFILE = "silly.lock"
NAME_RE = re.compile(r"^[a-z_][a-z0-9_]*$")
RESERVED = {"std", "main", "prelude"}


class Manifest:
    def __init__(self, root, data):
        self.root = root
        self.path = os.path.join(root, MANIFEST)
        pkg = data.get("package")
        if not isinstance(pkg, dict) or "name" not in pkg:
            raise SillyError(f"{self.path}: missing [package] name")
        self.name = pkg["name"]
        check_name(self.name, self.path)
        self.version = str(pkg.get("version", "0.0.0"))
        self.entry = os.path.join(root, pkg.get("entry", os.path.join("src", "main.silly")))
        self.src = os.path.join(root, "src")
        deps = data.get("dependencies", {})
        if not isinstance(deps, dict):
            raise SillyError(f"{self.path}: [dependencies] must be a table")
        self.deps = {}
        for name, spec in deps.items():
            check_name(name, self.path)
            if isinstance(spec, str):
                raise SillyError(f"{self.path}: dependency '{name}' needs a source",
                                 hint=f'write {name} = {{ path = "..." }} or {name} = {{ git = "..." }}')
            if not isinstance(spec, dict) or ("path" in spec) == ("git" in spec):
                raise SillyError(f"{self.path}: dependency '{name}' needs exactly one of `path` or `git`")
            if "rev" in spec and "git" not in spec:
                raise SillyError(f"{self.path}: dependency '{name}': `rev` only applies to git dependencies")
            unknown = set(spec) - {"path", "git", "rev"}
            if unknown:
                raise SillyError(f"{self.path}: dependency '{name}': unknown key '{sorted(unknown)[0]}'")
            self.deps[name] = spec


def check_name(name, where):
    if not NAME_RE.match(name) or name in RESERVED:
        raise SillyError(f"{where}: '{name}' is not a valid package name",
                         hint="use lowercase letters, digits and underscores; std, main and prelude are reserved")


def load_manifest(root):
    path = os.path.join(root, MANIFEST)
    try:
        with open(path, "rb") as f:
            data = tomllib.load(f)
    except OSError as e:
        raise SillyError(f"cannot read {path}: {e.strerror}")
    except tomllib.TOMLDecodeError as e:
        raise SillyError(f"{path}: {e}")
    return Manifest(os.path.realpath(root), data)


def find_root(start):
    """The nearest directory at or above `start` that holds a silly.toml."""
    d = os.path.realpath(start)
    if os.path.isfile(d):
        d = os.path.dirname(d)
    while True:
        if os.path.isfile(os.path.join(d, MANIFEST)):
            return d
        parent = os.path.dirname(d)
        if parent == d:
            return None
        d = parent


# ---- lockfile ----

def read_lock(root):
    path = os.path.join(root, LOCKFILE)
    if not os.path.exists(path):
        return {}
    try:
        with open(path, "rb") as f:
            data = tomllib.load(f)
    except tomllib.TOMLDecodeError as e:
        raise SillyError(f"{path}: {e}", hint="delete it and run `silly fetch` to regenerate it")
    return {p["name"]: p for p in data.get("package", [])}


def lock_text(pkgs):
    out = ["# Generated by `silly fetch`. Do not edit by hand.", "version = 1", ""]
    for name in sorted(pkgs):
        p = pkgs[name]
        out.append("[[package]]")
        out.append(f"name = {q(name)}")
        out.append(f"version = {q(p.version)}")
        out.append(f"source = {q(p.source)}")
        if p.req:
            out.append(f"requested = {q(p.req)}")
        if p.rev:
            out.append(f"rev = {q(p.rev)}")
        out.append("")
    return "\n".join(out)


def q(s):
    return json.dumps(s, ensure_ascii=False)


# ---- resolution ----

class Resolved:
    def __init__(self, name, source, dir_, rev=None, version="0.0.0"):
        self.name, self.source, self.dir, self.rev, self.version = name, source, dir_, rev, version
        self.by = self.req = None


def git(*args, cwd=None):
    r = subprocess.run(["git", *args], cwd=cwd, capture_output=True, text=True)
    if r.returncode != 0:
        msg = (r.stderr or r.stdout).strip().splitlines()
        raise SillyError(f"git {args[0]} failed: {msg[-1] if msg else 'exit ' + str(r.returncode)}")
    return r.stdout.strip()


def git_checkout(url, want, dest, quiet):
    """Make `dest` a checkout of `url` at `want` (a commit, tag or branch); return the commit."""
    if os.path.isdir(os.path.join(dest, ".git")):
        if git("config", "--get", "remote.origin.url", cwd=dest) != url:
            raise SillyError(f"{dest} is a checkout of a different repository",
                             hint="delete .silly/deps and run `silly fetch` again")
        if want and want_matches(dest, want):
            return git("rev-parse", "HEAD", cwd=dest)
        if not quiet:
            print(f"   updating {url}")
        git("fetch", "--quiet", "--tags", "--force", "origin", cwd=dest)
    else:
        if not quiet:
            print(f"    cloning {url}")
        os.makedirs(os.path.dirname(dest), exist_ok=True)
        git("clone", "--quiet", url, dest)
    if want:
        # A branch name should follow the remote, not a stale local branch.
        r = subprocess.run(["git", "rev-parse", "--verify", "--quiet", f"origin/{want}^{{commit}}"],
                           cwd=dest, capture_output=True, text=True)
        target = r.stdout.strip() if r.returncode == 0 else want
        git("checkout", "--quiet", "--detach", target, cwd=dest)
    else:
        git("checkout", "--quiet", "--detach", "origin/HEAD", cwd=dest)
    return git("rev-parse", "HEAD", cwd=dest)


def want_matches(dest, want):
    """True when `want` is a commit hash and the checkout is already there (no fetch needed)."""
    return re.fullmatch(r"[0-9a-f]{7,40}", want) is not None and git("rev-parse", "HEAD", cwd=dest).startswith(want)


def resolve(root, update=False, quiet=False, write_lock=True):
    """Resolve every dependency of the package at `root` (transitively).

    Returns (manifest, {name: Resolved}).  Uses silly.lock to pin git commits
    unless `update` is set, and rewrites the lockfile when the result changed.
    """
    top = load_manifest(root)
    lock = {} if update else read_lock(root)
    deps_dir = os.path.join(root, ".silly", "deps")
    out = {}
    queue = [(name, spec, top) for name, spec in top.deps.items()]
    while queue:
        name, spec, owner = queue.pop(0)
        if name == top.name:
            raise SillyError(f"{owner.path}: package '{top.name}' cannot depend on itself")
        if "path" in spec:
            d = os.path.realpath(os.path.join(owner.root, spec["path"]))
            if getattr(owner, "git_root", None) and os.path.relpath(d, owner.git_root).startswith(".."):
                raise SillyError(f"git dependency '{owner.name}' has a path dependency '{name}' "
                                 f"outside its repository", hint=f"{owner.name} should depend on {name} through git")
            source = "path+" + os.path.relpath(d, root)
            rev = None
        else:
            url = spec["git"]
            source = "git+" + url
            d = os.path.join(deps_dir, name)
            locked = lock.get(name)
            want = spec.get("rev")
            # The lock pins the commit only while silly.toml still asks for the same rev.
            if locked and locked.get("source") == source and locked.get("rev") \
                    and locked.get("requested") == spec.get("rev"):
                want = locked["rev"]
            rev = None  # filled after the conflict check below
        prev = out.get(name)
        if prev:
            if prev.source != source or (spec.get("rev") and prev.req and spec["rev"] != prev.req):
                raise SillyError(f"dependency '{name}' is required from two different sources",
                                 hint=f"{prev.source} (by {prev.by}) and {source} (by {owner.name})")
            continue
        if "git" in spec:
            rev = git_checkout(url, want, d, quiet)
        if not os.path.isfile(os.path.join(d, MANIFEST)):
            raise SillyError(f"dependency '{name}' at {d} has no {MANIFEST}")
        m = load_manifest(d)
        m.git_root = d if "git" in spec else getattr(owner, "git_root", None)
        if m.name != name:
            raise SillyError(f"dependency '{name}' at {d} is a package named '{m.name}'",
                             hint=f"name the dependency {m.name} in {owner.path}")
        r = Resolved(name, source, d, rev, m.version)
        r.by, r.req = owner.name, spec.get("rev")
        out[name] = r
        queue.extend((n, s, m) for n, s in m.deps.items())
    if write_lock:
        text = lock_text(out)
        path = os.path.join(root, LOCKFILE)
        old = open(path, encoding="utf-8").read() if os.path.exists(path) else None
        if text != old and (out or old is not None):
            with open(path, "w", encoding="utf-8") as f:
                f.write(text)
    return top, out


def package_paths(main_file):
    """{package name: src dir} for the package that holds `main_file`, or {} outside a package."""
    root = find_root(main_file)
    if root is None:
        return {}
    top, deps = resolve(root, quiet=True)
    paths = {top.name: top.src}
    for name, r in deps.items():
        paths[name] = os.path.join(r.dir, "src")
    return paths


# ---- manifest editing (keeps the user's comments and layout) ----

def set_dependency(root, name, spec):
    check_name(name, os.path.join(root, MANIFEST))
    m = load_manifest(root)
    if name == m.name:
        raise SillyError(f"package '{name}' cannot depend on itself")
    line = f"{name} = {{ " + ", ".join(f"{k} = {q(v)}" for k, v in spec.items()) + " }"
    edit_deps(root, name, line)


def remove_dependency(root, name):
    if name not in load_manifest(root).deps:
        raise SillyError(f"'{name}' is not a dependency of this package")
    edit_deps(root, name, None)


def edit_deps(root, name, line):
    path = os.path.join(root, MANIFEST)
    with open(path, encoding="utf-8") as f:
        lines = f.read().splitlines()
    start = next((i for i, l in enumerate(lines) if l.strip() == "[dependencies]"), None)
    if start is None:
        if line is None:
            return
        while lines and not lines[-1].strip():
            lines.pop()
        lines += ["", "[dependencies]", line]
    else:
        end = next((i for i in range(start + 1, len(lines)) if lines[i].lstrip().startswith("[")), len(lines))
        key = re.compile(rf"^\s*{re.escape(name)}\s*=")
        hit = next((i for i in range(start + 1, end) if key.match(lines[i])), None)
        if hit is not None:
            if line is None:
                del lines[hit]
            else:
                lines[hit] = line
        elif line is not None:
            last = start
            for i in range(start + 1, end):
                if lines[i].strip():
                    last = i
            lines.insert(last + 1, line)
    text = "\n".join(lines) + "\n"
    try:
        Manifest(root, tomllib.loads(text))
    except tomllib.TOMLDecodeError as e:
        raise SillyError(f"editing {path} would make it invalid: {e}")
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)


# ---- `silly new` ----

def new_package(path, lib=False):
    name = os.path.basename(os.path.abspath(path)).replace("-", "_")
    check_name(name, path)
    if os.path.exists(path) and os.listdir(path):
        raise SillyError(f"{path} already exists and is not empty")
    os.makedirs(os.path.join(path, "src"), exist_ok=True)
    os.makedirs(os.path.join(path, "tests"), exist_ok=True)
    with open(os.path.join(path, MANIFEST), "w", encoding="utf-8") as f:
        f.write(f'[package]\nname = "{name}"\nversion = "0.1.0"\n\n[dependencies]\n')
    with open(os.path.join(path, ".gitignore"), "w", encoding="utf-8") as f:
        f.write(".silly/\n")
    if lib:
        with open(os.path.join(path, "src", "lib.silly"), "w", encoding="utf-8") as f:
            f.write(f'# The {name} library. Other packages use it with `import {name}`.\n\n'
                    'fn add(a: int, b: int) -> int:\n    return a + b\n')
        with open(os.path.join(path, "tests", "lib_test.silly"), "w", encoding="utf-8") as f:
            f.write(f'from {name} import add\n\n@test\nfn adds():\n    assert add(2, 3) == 5\n')
    else:
        with open(os.path.join(path, "src", "main.silly"), "w", encoding="utf-8") as f:
            f.write(f'fn main():\n    print("hello from {name}")\n')
    return name


def test_files(root):
    """Every .silly file under src/ and tests/ that defines an @test function."""
    found = []
    for sub in ("src", "tests"):
        for dp, dns, fns in os.walk(os.path.join(root, sub)):
            dns.sort()
            for fn in sorted(fns):
                if fn.endswith(".silly"):
                    p = os.path.join(dp, fn)
                    with open(p, encoding="utf-8") as f:
                        if re.search(r"^\s*@test\b", f.read(), re.M):
                            found.append(p)
    return found
